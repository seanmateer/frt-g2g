export const getTrailCenterById = (id: string): TrailCenter | undefined => {
  return trailCenters.find((tc) => tc.id === id);
};

export const getTrailCentersByRegion = (region: string): TrailCenter[] => {
  return trailCenters.filter((tc) => tc.region === region);
};

export const getAllRegions = (): string[] => {
  return [...new Set(trailCenters.map((tc) => tc.region))].sort();
};
